#!/usr/bin/env node
/**
 * render-github-cleanup.js — free worker repos' Actions storage + local temp files
 * after an approved render.
 *
 * Usage:
 *   node scripts/render-github-cleanup.js --slug=<slug>                  # clean ALL workers that rendered this slug + local temp + orphan audio
 *   node scripts/render-github-cleanup.js --slug=<slug> --worker=<id>    # single worker
 *   node scripts/render-github-cleanup.js --worker=<id> --all            # sweep completed runs on that worker (skips other books' in-flight renders; --force-all overrides)
 *   node scripts/render-github-cleanup.js --worker=<id> --run=<id>       # specific run
 *   node scripts/render-github-cleanup.js --audio-only                   # only clean orphan audio files
 */
const fs = require("fs");
const path = require("path");
const { ROOT, loadAccounts, resolveWorker, repoOf, gh, parseArgs } = require("./lib/render-pool");

const args = parseArgs(process.argv.slice(2));
const acc = loadAccounts();
const slug = args.slug;

// ── Audio cleanup: delete public/audio files not referenced by any book ─────
function cleanOrphanAudio() {
  const audioDir = path.join(ROOT, "public", "audio");
  if (!fs.existsSync(audioDir)) return;

  const booksDir = path.join(ROOT, "books");
  const registeredSlugs = new Set();
  if (fs.existsSync(booksDir)) {
    for (const d of fs.readdirSync(booksDir, { withFileTypes: true })) {
      if (d.isDirectory()) registeredSlugs.add(d.name);
    }
  }

  const audioFiles = fs.readdirSync(audioDir);
  let deleted = 0, freedMB = 0;
  for (const f of audioFiles) {
    const ext = path.extname(f).toLowerCase();
    if (![".m4a", ".mp3", ".wav", ".ogg", ".aac", ".flac"].includes(ext)) continue;

    // mastered files are always safe to delete (gitignored, regenerated by runner)
    const isMastered = f.includes(".mastered.");
    // check if base name matches any registered book slug
    const baseName = f.replace(/\.mastered/, "").replace(ext, "");
    const isRegistered = registeredSlugs.has(baseName);

    if (isMastered || !isRegistered) {
      const fp = path.join(audioDir, f);
      const sizeMB = fs.statSync(fp).size / 1e6;
      try {
        fs.unlinkSync(fp);
        deleted++;
        freedMB += sizeMB;
        const reason = isMastered ? "mastered (gitignored)" : "orphan (no book)";
        console.log(`  🗑 ${f} (${sizeMB.toFixed(1)} MB) — ${reason}`);
      } catch (e) {
        console.warn(`  ⚠ ${f} silinemedi: ${e.message}`);
      }
    }
  }
  if (deleted > 0) console.log(`  ✓ Audio: ${deleted} dosya silindi (~${freedMB.toFixed(0)} MB)`);
  else console.log(`  ✓ Audio: orphan dosya yok, temiz.`);
}

// ── Audio-only mode ─────────────────────────────────────────────────────────
if (args["audio-only"]) {
  console.log("\n🔊 Orphan audio temizliği...");
  cleanOrphanAudio();
  process.exit(0);
}

// ── Local temp cleanup ──────────────────────────────────────────────────────
function cleanLocal(s) {
  let cleaned = 0;
  // assemble temp dir
  const asmDir = path.join(ROOT, "out", `gh-asm-${s}`);
  if (fs.existsSync(asmDir)) {
    fs.rmSync(asmDir, { recursive: true, force: true });
    console.log(`  🗑 ${asmDir}`);
    cleaned++;
  }
  // split state files
  for (const f of [`.render-github-split.${s}.json`, ".render-github-split.json"]) {
    const fp = path.join(ROOT, f);
    if (fs.existsSync(fp)) {
      try {
        const st = JSON.parse(fs.readFileSync(fp, "utf8"));
        if (st.slug === s) { fs.unlinkSync(fp); console.log(`  🗑 ${f}`); cleaned++; }
      } catch { fs.unlinkSync(fp); cleaned++; }
    }
  }
  // slug-specific audio + captions (baked into the mp4, no longer needed)
  const slugAudioExts = [".m4a", ".mp3", ".wav", ".ogg", ".aac", ".flac"];
  for (const ext of slugAudioExts) {
    for (const variant of [`${s}${ext}`, `${s}.mastered${ext}`]) {
      const fp = path.join(ROOT, "public", "audio", variant);
      if (fs.existsSync(fp)) {
        const mb = (fs.statSync(fp).size / 1e6).toFixed(1);
        fs.unlinkSync(fp); cleaned++;
        console.log(`  🗑 public/audio/${variant} (${mb} MB)`);
      }
    }
  }
  // slug-specific captions
  const captDir = path.join(ROOT, "public", "captions");
  if (fs.existsSync(captDir)) {
    for (const f of fs.readdirSync(captDir)) {
      if (f.startsWith(s + ".") || f === s + ".vtt") {
        const fp = path.join(captDir, f);
        fs.unlinkSync(fp); cleaned++;
        console.log(`  🗑 public/captions/${f}`);
      }
    }
  }
  // render state
  const statePath = path.join(ROOT, ".render-github-state.json");
  if (fs.existsSync(statePath)) {
    try {
      const st = JSON.parse(fs.readFileSync(statePath, "utf8"));
      if (!s || st.slug === s) { fs.unlinkSync(statePath); cleaned++; }
    } catch {}
  }
  if (cleaned > 0) console.log(`  ✓ Local: ${cleaned} temp dosya/klasör silindi`);
}

/**
 * Slugs with an IN-FLIGHT split render, i.e. a `.render-github-split.<slug>.json` whose
 * assembled `out/<slug>.mp4` does not exist yet. Their artifacts are the ONLY copy of
 * that render — deleting one costs another agent a full segment re-render.
 *
 * This exists because a `--worker=X --all` sweep meant for one book deleted another
 * agent's in-flight `the-stranger` seg1 artifacts (2026-09-04). Several agents share
 * this pool, so a blunt sweep is never safe; protect by slug.
 */
function inFlightSlugs() {
  const out = new Set();
  for (const f of fs.readdirSync(ROOT)) {
    const m = f.match(/^\.render-github-split\.(.+)\.json$/);
    if (!m) continue;
    const s = m[1];
    if (s === slug) continue; // the book we were explicitly told to clean
    if (!fs.existsSync(path.join(ROOT, "out", `${s}.mp4`))) out.add(s);
  }
  return out;
}

/** Does this run's ref belong to a protected in-flight slug? */
function isProtected(run, protectedSlugs) {
  const ref = String(run.headBranch || "");
  for (const s of protectedSlugs) if (ref.startsWith(`render/${s}-seg`) || ref === `render/${s}`) return s;
  return null;
}

// ── GitHub cleanup helpers ──────────────────────────────────────────────────
function cleanWorker(worker, runFilter) {
  const repo = repoOf(worker);
  let runs;
  try {
    runs = gh(worker, ["run", "list", "--repo", repo, "--workflow", "render-video.yml", "-L", "100",
      "--json", "databaseId,status,conclusion,headBranch"], { json: true }) || [];
  } catch (e) {
    console.warn(`  ⚠ @${worker.username}: run list alınamadı (${String(e.message).slice(0, 80)})`);
    return { art: 0, run: 0, freed: 0 };
  }

  let toClean = runFilter ? runs.filter(runFilter) : runs.filter(r => r.status === "completed");

  // Never delete artifacts belonging to another book's in-flight render (see
  // inFlightSlugs). --force-all overrides, for when you really mean every run.
  if (!args["force-all"]) {
    const protectedSlugs = inFlightSlugs();
    if (protectedSlugs.size) {
      const kept = new Map();
      toClean = toClean.filter((r) => {
        const s = isProtected(r, protectedSlugs);
        if (s) kept.set(s, (kept.get(s) || 0) + 1);
        return !s;
      });
      for (const [s, n] of kept) {
        console.log(`  🛡  @${worker.username}: ${n} run korundu — "${s}" render'ı devam ediyor (out/${s}.mp4 yok)`);
      }
    }
  }
  if (!toClean.length) return { art: 0, run: 0, freed: 0 };

  let delArt = 0, delRun = 0, freed = 0;
  for (const run of toClean) {
    // delete artifacts
    try {
      const raw = gh(worker, ["api", `/repos/${repo}/actions/runs/${run.databaseId}/artifacts`,
        "--jq", ".artifacts[] | {id:.id,name:.name,size:.size_in_bytes}"]);
      const arts = raw.trim().split("\n").filter(Boolean).map(l => JSON.parse(l));
      for (const a of arts) {
        try {
          gh(worker, ["api", "-X", "DELETE", `/repos/${repo}/actions/artifacts/${a.id}`]);
          freed += a.size || 0; delArt++;
        } catch {}
      }
    } catch {}
    // delete run
    try {
      gh(worker, ["api", "-X", "DELETE", `/repos/${repo}/actions/runs/${run.databaseId}`]);
      delRun++;
    } catch {}
  }
  return { art: delArt, run: delRun, freed };
}

// ── Main: slug-based cleanup (all workers) ──────────────────────────────────
if (slug && !args.worker && !args.run) {
  // Find split state to know which workers were involved
  const perSlug = path.join(ROOT, `.render-github-split.${slug}.json`);
  const splitPath = fs.existsSync(perSlug) ? perSlug : path.join(ROOT, ".render-github-split.json");
  let segments = [];
  if (fs.existsSync(splitPath)) {
    try {
      const st = JSON.parse(fs.readFileSync(splitPath, "utf8"));
      if (st.slug === slug) segments = st.segments || [];
    } catch {}
  }

  const workers = (acc.workers || []).filter(w => w.active !== false && w.token);
  const involvedUsernames = new Set(segments.map(s => s.username));
  const targetWorkers = involvedUsernames.size > 0
    ? workers.filter(w => involvedUsernames.has(w.username))
    : workers;

  console.log(`\n🧹 Temizlik — ${slug} (${targetWorkers.length} worker + local + audio)\n`);

  let totalArt = 0, totalRun = 0, totalFreed = 0;
  for (const w of targetWorkers) {
    const segRef = slug ? `render/${slug}-seg` : null;
    const filter = segRef
      ? r => r.status === "completed" && r.headBranch && r.headBranch.startsWith(segRef)
      : r => r.status === "completed";

    process.stdout.write(`  @${w.username}... `);
    const { art, run, freed } = cleanWorker(w, filter);
    totalArt += art; totalRun += run; totalFreed += freed;
    console.log(`${run} run, ${art} artifact silindi`);
  }

  console.log(`\n✓ GitHub: ${totalArt} artifact + ${totalRun} run · ~${(totalFreed / 1e6).toFixed(0)} MB boşaldı\n`);

  // Local temp
  console.log("📁 Local temp temizliği...");
  cleanLocal(slug);

  // Orphan audio — OPT-IN ONLY. This sweep is repo-wide: it deletes every book's
  // *.mastered.m4a, not just this slug's. With 3-5 books in flight across agents at
  // once, a slug-scoped cleanup must not touch another book's files, so it no longer
  // runs by default. (Mastered files are derived + gitignored and the runner remasters
  // from raw, so this was never data loss — but it is still not ours to delete here.)
  if (args["orphan-audio"]) {
    console.log("\n🔊 Orphan audio temizliği (--orphan-audio; repo geneli)...");
    cleanOrphanAudio();
  }

  console.log(`\n✅ ${slug} tamamen temizlendi (sadece bu kitabın dosyaları).`);
  process.exit(0);
}

// ── Legacy single-worker mode ───────────────────────────────────────────────
let worker, runIds = [];
const statePath = path.join(ROOT, ".render-github-state.json");
let state = null;
try { state = JSON.parse(fs.readFileSync(statePath, "utf8")); } catch {}

if (args.worker) {
  worker = resolveWorker(acc, args.worker);
} else if (state && (!slug || slug === state.slug)) {
  worker = resolveWorker(acc, state.workerId);
} else {
  worker = resolveWorker(acc, "last");
}
const repo = repoOf(worker);

if (args.all) {
  const runs = gh(worker, ["run", "list", "--repo", repo, "--workflow", "render-video.yml", "-L", "100",
    "--json", "databaseId,status"], { json: true }) || [];
  runIds = runs.filter(r => r.status === "completed").map(r => r.databaseId);
} else if (args.run) {
  runIds = [Number(args.run)];
} else if (state && (!slug || slug === state.slug) && state.runId) {
  runIds = [Number(state.runId)];
} else {
  console.error("Ne temizlenecek belli değil. Ver: --slug=<slug> | --worker=<id> --all | --run=<id>");
  process.exit(1);
}

console.log(`🧹 Temizlik — ${repo} (worker ${worker.name || worker.id}) · ${runIds.length} çalışma`);

let freed = 0, delArt = 0, delRun = 0;
for (const id of runIds) {
  let arts = [];
  try {
    const raw = gh(worker, ["api", `/repos/${repo}/actions/runs/${id}/artifacts`,
      "--jq", ".artifacts[] | {id:.id,name:.name,size:.size_in_bytes}"]);
    arts = raw.trim().split("\n").filter(Boolean).map(l => JSON.parse(l));
  } catch {}
  for (const a of arts) {
    try {
      gh(worker, ["api", "-X", "DELETE", `/repos/${repo}/actions/artifacts/${a.id}`]);
      freed += a.size || 0; delArt++;
      console.log(`  🗑 artifact "${a.name}" (${((a.size || 0) / 1e6).toFixed(0)} MB)`);
    } catch (e) { console.warn(`  ⚠ artifact ${a.id} silinemedi: ${String(e.message).slice(0, 120)}`); }
  }
  try {
    gh(worker, ["api", "-X", "DELETE", `/repos/${repo}/actions/runs/${id}`]);
    delRun++; console.log(`  🗑 run ${id}`);
  } catch (e) {
    console.warn(`  ⚠ run ${id} silinemedi: ${String(e.message).slice(0, 120)}`);
  }
}

console.log(`\n✓ Silinen: ${delArt} artifact + ${delRun} run · ~${(freed / 1e6).toFixed(0)} MB boşaldı.`);
if (state && (!slug || slug === state.slug)) {
  try { fs.unlinkSync(statePath); } catch {}
}
console.log(`✅ Havuz slotu (${repo}) bir sonraki render'a hazır.`);
