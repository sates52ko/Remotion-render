const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const dir = path.resolve('out', `clock-regression-${Date.now()}`);
fs.mkdirSync(dir, { recursive: true });
const run = (p, a) => execFileSync(p, a, { encoding: 'utf8', maxBuffer: 1024 * 1024 });
const clip = path.join(dir, 'clip.mp4'), audio = path.join(dir, 'audio.m4a');
run('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=64x64:rate=30', '-frames:v', '30', '-c:v', 'libx264', '-bf', '2', clip]);
run('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000', '-t', '2', '-c:a', 'aac', audio]);
const list = path.join(dir, 'parts.txt');
fs.writeFileSync(list, `file '${clip.replace(/\\/g, '/')}'\nduration 1.5\nfile '${clip.replace(/\\/g, '/')}'\n`);
const input = path.join(dir, 'gapped.mp4'), output = path.join(dir, 'normalized.mp4');
run('ffmpeg', ['-y', '-v', 'error', '-f', 'concat', '-safe', '0', '-i', list, '-c', 'copy', input]);
const options = [`--video=${input}`, `--audio=${audio}`, `--out=${output}`, '--fps=30'];
const missing = spawnSync('node', ['scripts/normalize-render-clock.js', ...options, '--frames=59'], { encoding: 'utf8' });
assert.notEqual(missing.status, 0);
assert.match(missing.stderr, /Frame count mismatch/);
assert(!fs.existsSync(output));
run('node', ['scripts/normalize-render-clock.js', ...options, '--frames=60']);
const probe = file => JSON.parse(run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', file]));
assert(Number(probe(input).format.duration) > 2.4);
assert(Math.abs(Number(probe(output).format.duration) - 2) < 0.1);
const hash = file => run('ffmpeg', ['-v', 'error', '-i', file, '-map', '0:v:0', '-c:v', 'copy', '-f', 'hash', '-hash', 'SHA256', '-']).trim();
assert.equal(hash(input), hash(output));
assert(fs.existsSync(input));
console.log('PASS clock repair: real concat gap corrected, B-frame encoded payload preserved, missing frames rejected, evidence retained');
