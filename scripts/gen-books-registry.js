#!/usr/bin/env node
/**
 * gen-books-registry.js — scans books/<slug>/ and writes src/books.generated.ts,
 * which Root.tsx maps over to register Remotion compositions per book:
 *   - config.vox.json       → BOOKS (VoxBook + VoxThumbnail)          → Vox-<slug>
 *   - config.antidote.json  → ANTIDOTE_BOOKS (AntidoteBook)           → Antidote-<slug>
 *
 * A book's book.json `engine` field is the pipeline's source of truth for which
 * engine to build/publish; the registry still registers whatever configs exist
 * so both can be previewed side by side in Studio during a switch.
 *
 * Run automatically by scripts/make-book.js; safe to run standalone.
 */
const fs = require("fs");
const path = require("path");
const { ROOT, rel, abs, listVoxSlugs, listAntidoteSlugs, readManifest } = require("./lib/paths");

const ident = (s) => s.replace(/[^a-zA-Z0-9]/g, "_");
const imp = (p) => `../${p}`; // src/books.generated.ts → repo-relative import

// book.json is the pipeline's source of truth for engine + palette. Read it per
// slug so the generated registry can carry each book's chosen engine (decides
// which thumbnail component renders) and its bespoke palette (kills the
// "every thumbnail is red-on-cream" sameness — see resolvePalette in voxkit).
const manifestOf = (slug) => readManifest(slug) || {};
const engineOf = (slug) => {
  const e = String(manifestOf(slug).engine || "").toLowerCase();
  return e === "antidote" ? "antidote" : "vox"; // missing/none → vox (shipped default)
};

const voxBooks = listVoxSlugs().map((slug) => ({
  slug,
  cfgPath: rel.voxConfig(slug),
  metaPath: fs.existsSync(abs.youtubeMeta(slug)) ? rel.youtubeMeta(slug) : null,
  engine: engineOf(slug),
}));
const antidoteBooks = listAntidoteSlugs().map((slug) => ({
  slug,
  cfgPath: rel.antidoteConfig(slug),
  metaPath: fs.existsSync(abs.youtubeMeta(slug)) ? rel.youtubeMeta(slug) : null,
  engine: engineOf(slug),
}));

// Palette map for EVERY known book (union of both engines), pulled from book.json.
const allSlugs = [...new Set([...voxBooks.map((b) => b.slug), ...antidoteBooks.map((b) => b.slug)])].sort();
const paletteEntries = allSlugs
  .map((slug) => {
    const p = manifestOf(slug).palette;
    if (!p || !p.paper) return null;
    const ch = p.captionHighlight ? `, captionHighlight: '${p.captionHighlight}'` : "";
    return `  '${slug}': { paper: '${p.paper}', ink: '${p.ink}', red: '${p.red}', gold: '${p.gold}'${ch} },`;
  })
  .filter(Boolean)
  .join("\n");

// Per-book background tint opt-in (book.json.bgTint === true). Absent/false → the
// original plain shared paper background, so existing books look identical. New
// books get bgTint:true written by make-prompt, so the tint is on going forward.
const bgTintEntries = allSlugs
  .filter((slug) => manifestOf(slug).bgTint === true)
  .map((slug) => `  '${slug}': true,`)
  .join("\n");

// ── imports ──────────────────────────────────────────────────────────────
const voxImports = voxBooks
  .map((b) => {
    const lines = [`import cfg_${ident(b.slug)} from '${imp(b.cfgPath)}';`];
    if (b.metaPath) lines.push(`import meta_${ident(b.slug)} from '${imp(b.metaPath)}';`);
    return lines.join("\n");
  })
  .join("\n");
const antImports = antidoteBooks
  .map((b) => {
    const lines = [`import ant_${ident(b.slug)} from '${imp(b.cfgPath)}';`];
    if (b.metaPath) lines.push(`import ant_meta_${ident(b.slug)} from '${imp(b.metaPath)}';`);
    return lines.join("\n");
  })
  .join("\n");

// ── entries ──────────────────────────────────────────────────────────────
const voxEntries = voxBooks
  .map(
    (b) =>
      `  {\n    slug: '${b.slug}',\n    engine: '${b.engine}',\n    config: cfg_${ident(b.slug)} as any,\n    meta: ${b.metaPath ? `meta_${ident(b.slug)} as any` : "null"},\n  },`,
  )
  .join("\n");
const antEntries = antidoteBooks
  .map(
    (b) =>
      `  {\n    slug: '${b.slug}',\n    engine: '${b.engine}',\n    config: ant_${ident(b.slug)} as any,\n    meta: ${b.metaPath ? `ant_meta_${ident(b.slug)} as any` : "null"},\n  },`,
  )
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-books-registry.js — do not edit by hand.
// Regenerate with: node scripts/gen-books-registry.js
${voxImports}
${antImports}

export type Palette = { paper: string; ink: string; red: string; gold: string; captionHighlight?: string };

export type BookEntry = {
  slug: string;
  engine: 'vox' | 'antidote';
  config: any;
  meta: any | null;
};

export type AntidoteBookEntry = {
  slug: string;
  engine: 'vox' | 'antidote';
  config: any;
  meta?: any | null;
};

// Per-book palettes (from books/<slug>/book.json). resolvePalette() in voxkit and
// the Antidote thumbnail read this so each book has its own color identity.
export const BOOK_PALETTES: Record<string, Palette> = {
${paletteEntries}
};

// Books opted into the palette-tinted background (new books; see book.json.bgTint).
export const BOOK_BG_TINT: Record<string, boolean> = {
${bgTintEntries}
};

export const BOOKS: BookEntry[] = [
${voxEntries}
];

export const ANTIDOTE_BOOKS: AntidoteBookEntry[] = [
${antEntries}
];
`;

// Write with retry: an editor/dev-server holding this file open makes Windows fail the
// open with EBUSY/EPERM/UNKNOWN, which used to abort the WHOLE make-book run at step 7
// (after images + meta + thumbnail were already generated) and had to be fixed by hand.
// The lock is always transient, so back off and retry instead of dying.
const OUT_FILE = path.join(ROOT, "src", "books.generated.ts");
function writeWithRetry(file, data, tries = 6) {
  for (let i = 1; ; i++) {
    try {
      fs.writeFileSync(file, data);
      if (i > 1) console.log(`  (dosya kilidi ${i}. denemede açıldı)`);
      return;
    } catch (e) {
      const locked = ["EBUSY", "EPERM", "EACCES", "UNKNOWN"].includes(e.code);
      if (!locked || i >= tries) throw e;
      console.warn(`  ⚠ ${path.basename(file)} kilitli (${e.code}) — ${i}/${tries}, 1.5s sonra tekrar...`);
      // Synchronous sleep: this script is sync end-to-end and callers exec it directly.
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1500);
    }
  }
}
try {
  writeWithRetry(OUT_FILE, out);
} catch (e) {
  console.error(`\n❌ src/books.generated.ts yazılamadı (${e.code || e.message}).`);
  console.error(`   Dosyayı açık tutan bir editör/dev-server'ı kapatıp tekrar dene:`);
  console.error(`   node scripts/gen-books-registry.js`);
  process.exit(1);
}
console.log(
  `✓ src/books.generated.ts — Vox: ${voxBooks.length} (${voxBooks.map((b) => b.slug).join(", ") || "none"}) · ` +
    `Antidote: ${antidoteBooks.length} (${antidoteBooks.map((b) => b.slug).join(", ") || "none"})`,
);
