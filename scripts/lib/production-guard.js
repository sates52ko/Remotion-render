/**
 * production-guard.js — every production entry point starts here (storyboard prep/merge, make-book, render,
 * mute-test prep, preview-ready). It answers "which code is this run using?" and refuses to run on code
 * that is not a commit.
 *
 * Why (2026-10-16/17): HEAD said one thing and the disk ran another. A `git stash -u` and later a mixed
 * `git reset origin/god-mode` in the shared main checkout left HEAD at the new commit while 20 engine files
 * on disk were older versions and 18 new files were missing — every agent there silently ran the old engine.
 *
 * Rule: in the shared main checkout, a tracked code file that differs from HEAD (modified or deleted), or an
 * untracked file under scripts/lib/ or src/ (it can be require()d), STOPS the run with the list of files and,
 * when a file equals an older commit, which one. It never fixes anything itself (no reset, no checkout).
 * Deliberate local code: PRODUCTION_ALLOW_DIRTY="<reason>" or --allow-dirty-code="<reason>" (recorded).
 * In a linked git worktree (development) it warns instead of stopping. Skipped inside GitHub Actions
 * (render workers run an isolated bundle commit) and with PRODUCTION_GUARD=off (tests only).
 *
 * Every run is recorded in books/<slug>/pipeline-record.json: step, HEAD, the scripts/ and src/ tree ids,
 * the dirty state and its content hash, and how far HEAD is behind the local origin/god-mode ref.
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const CODE_ROOT = path.join(__dirname, "..", "..");
const CODE_PATHS = ["scripts", "src", "data/quality-policy.json", "data/icon-readings.json"];
const IGNORE = new Set(["src/books.generated.ts"]); // regenerated by gen-books-registry on every book

function git(argv, cwd = CODE_ROOT) {
  try { return execFileSync("git", argv, { cwd, stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 * 1024 * 1024 }).toString(); } catch { return null; }
}

function codeState(root = CODE_ROOT) {
  const head = (git(["rev-parse", "HEAD"], root) || "").trim() || null;
  const status = (git(["status", "--porcelain", "--untracked-files=all", "--", ...CODE_PATHS], root) || "").split("\n").filter(Boolean);
  const drift = [], notes = [];
  for (const line of status) {
    const code = line.slice(0, 2), file = line.slice(3).trim().replace(/^"|"$/g, "");
    if (IGNORE.has(file)) continue;
    if (code === "??") {
      // dot-files (scratch like scripts/lib/.firewall-baseline-test.js) are never require()d by name
      if (/^(scripts\/lib\/|src\/)/.test(file) && !path.basename(file).startsWith(".")) drift.push({ file, change: "untracked (can be required)" });
      else notes.push(file);
      continue;
    }
    drift.push({ file, change: /D/.test(code) ? "deleted" : "modified" });
  }
  const gitDir = (git(["rev-parse", "--git-dir"], root) || "").trim();
  const commonDir = (git(["rev-parse", "--git-common-dir"], root) || "").trim();
  const linkedWorktree = !!gitDir && !!commonDir && path.resolve(root, gitDir) !== path.resolve(root, commonDir);
  const behind = parseInt((git(["rev-list", "--count", "HEAD..refs/remotes/origin/god-mode"], root) || "").trim(), 10);
  return { head, drift, notes, linkedWorktree, behindOrigin: Number.isFinite(behind) ? behind : null,
    scriptsTree: (git(["rev-parse", "HEAD:scripts"], root) || "").trim() || null,
    srcTree: (git(["rev-parse", "HEAD:src"], root) || "").trim() || null };
}

// For a drifted file: is its disk content an older committed version? (the reset/stash signature)
function olderCommitOf(file, root = CODE_ROOT) {
  const abs = path.join(root, file);
  if (!fs.existsSync(abs)) return null;
  const blob = (git(["hash-object", "--", file], root) || "").trim();
  for (const c of (git(["log", "-n", "40", "--format=%h", "--", file], root) || "").split("\n").filter(Boolean)) {
    if ((git(["rev-parse", `${c}:${file}`], root) || "").trim() === blob) return c;
  }
  return null;
}

function productionGuard({ slug, step, argv = process.argv, root = CODE_ROOT } = {}) {
  if (process.env.GITHUB_ACTIONS || process.env.PRODUCTION_GUARD === "off") return null;
  const st = codeState(root);
  if (!st.head) return null; // not a git checkout (e.g. an exported bundle)
  const flag = (argv.find((a) => a.startsWith("--allow-dirty-code=")) || "").slice("--allow-dirty-code=".length);
  const allowReason = (process.env.PRODUCTION_ALLOW_DIRTY || flag || "").trim() || null;
  const record = { step, at: new Date().toISOString(), head: st.head, scriptsTree: st.scriptsTree, srcTree: st.srcTree,
    behindOrigin: st.behindOrigin, linkedWorktree: st.linkedWorktree, dirty: st.drift.length, allowReason };
  if (st.drift.length) {
    const fp = require("./code-fingerprint").codeFingerprint(root, CODE_PATHS);
    record.treeSha256 = fp.treeSha256;
    record.driftFiles = st.drift.slice(0, 40).map((d) => d.file);
  }
  if (slug) {
    const p = path.join(root, "books", slug, "pipeline-record.json");
    if (fs.existsSync(path.dirname(p))) {
      let rec = { note: "production-guard.js: which code each pipeline step ran on", runs: [] };
      try { rec = JSON.parse(fs.readFileSync(p, "utf8")); } catch {}
      rec.runs = (rec.runs || []).concat([record]).slice(-80);
      try { fs.writeFileSync(p, JSON.stringify(rec, null, 2) + "\n"); } catch {}
    }
  }
  const short = st.head.slice(0, 7);
  if (st.behindOrigin > 0) console.warn(`⚠ production-guard: HEAD ${short} is ${st.behindOrigin} commit(s) behind origin/god-mode (as last fetched). New engine fixes are not in this checkout.`);
  if (!st.drift.length) { console.log(`· production-guard: ${step} on ${short} (code = HEAD)`); return record; }
  const lines = st.drift.slice(0, 25).map((d) => {
    const older = d.change === "modified" ? olderCommitOf(d.file, root) : null;
    return `   - ${d.file} — ${d.change}${older ? ` (disk = the version from ${older}: an OLD copy, likely a stash/reset leftover)` : ""}`;
  });
  const msg = [`production-guard: ${st.drift.length} code file(s) on disk differ from HEAD ${short} (${step}):`, ...lines,
    st.drift.length > 25 ? `   … and ${st.drift.length - 25} more` : null,
    "   This run would use code that is not a commit. Nothing was changed.",
    "   If they are old copies: restore them from HEAD (git checkout HEAD -- <files>) after checking with the owner in AGENT_LOG.md.",
    "   If it is your deliberate local change: commit it, or rerun with PRODUCTION_ALLOW_DIRTY=\"<reason>\" (recorded)."].filter(Boolean).join("\n");
  if (allowReason) { console.warn(`⚠ ${msg}\n   ALLOWED: ${allowReason}`); return record; }
  if (st.linkedWorktree) { console.warn(`⚠ ${msg}\n   (linked worktree = development: warning only)`); return record; }
  console.error(`❌ ${msg}`);
  process.exit(2);
}

module.exports = { productionGuard, codeState, olderCommitOf, CODE_PATHS };
